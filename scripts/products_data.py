# ── 其余产品：按 PRD 一级模块树派生（子模块清单就是 PRD 的子节点，不另编内容）──
# 各模块的"列标签"按模块语义给（筛查类看项目/日期/结果；管理类看事项/时间/状态；
# 报表类看口径/本期/上期；转诊类看对象/转诊去向/状态）。
_MODULE_COLS = {
    "screen": ["项目", "日期", "结果"],
    "manage": ["事项", "最近处理", "责任人"],
    "report": ["统计口径", "本周期", "上周期"],
    "refer": ["转诊事项", "转入机构", "状态说明"],
    "visit": ["访视项目", "访视日期", "结果"],
}
_MODULE_KIND = [
    (("筛查", "检查", "检验", "体检", "评估"), "screen"),
    (("报表", "统计"), "report"),
    (("转诊",), "refer"),
    (("访视",), "visit"),
]
_KPI_TONES = ("info", "accent", "attention", "positive", "special")


def _module_kind(name: str) -> str:
    for keys, kind in _MODULE_KIND:
        if any(k in name for k in keys):
            return kind
    return "manage"


def _demo_count(pid: str, mod_i: int, i: int) -> str:
    """确定性的演示计数：同一产品/模块/位置永远同值（避免每次构建数字乱跳）。"""
    base = 86 + (sum(ord(c) for c in pid) % 40) * 12
    return "{:,}".format(base + mod_i * 137 + i * 43)


def module_pages(pid: str, pd: dict, d: dict, caps: list, doctor: str) -> list:
    """该产品的业务模块页列表：手写优先（MODULE_PAGES），其余按 PRD 模块树派生。

    派生规则（保证"每页都有真内容"，不出现只有一行的空壳页）：
      · 模块名 = PRD 一级模块名；子模块清单 = PRD 子节点（权威信息架构）；
      · 有子节点的模块 → 行 = 子节点 × 演示对象；无子节点的模块（如「检查结果」「随访管理」）
        → 行 = 该产品演示队列里的事项（产品相关，不另编事项名）；
      · KPI 优先用该产品自己的指标（`DEMO.kpis`），不足时按子节点补。
    """
    if MODULE_PAGES.get(pid):
        return MODULE_PAGES[pid]
    tree = pd.get("tree") or []
    names = [(n, s) for n, s in tree if n not in SKIP_MODULES]
    if not names:                      # p06 这类没有模块树的：用 caps 作模块名
        names = [(n, []) for n in (caps or [])][:6]
    demo_rows = d.get("rows", [])
    people = [r["who"].split(" · ")[0] for r in demo_rows] or ["李慧"]
    things = [r["item"] for r in demo_rows] or ["本周期台账"]
    out = []
    for mi, (name, subs) in enumerate(names):
        # 「××工作台 / ××档案」就是既有的对象视图，不重复进业务菜单
        if name.endswith("工作台") or name.endswith("档案"):
            continue
        kind = _module_kind(name)
        cols = list(_MODULE_COLS[kind])
        items = subs if subs else things
        rows = []
        for i, it in enumerate(items[:5]):
            who = people[i % len(people)]
            if kind == "screen":
                mid = ["%s · %s" % (name, it) if not subs else it,
                       "%02d-%02d" % (4 + (mi + i) % 3, 8 + i * 3),
                       ["待出结果", "未见异常", "可疑 · 待复核", "已出结果", "建议复查"][i % 5]]
            elif kind == "report":
                mid = [it, _demo_count(pid, mi, i), _demo_count(pid, mi, i + 1)]
            elif kind == "refer":
                mid = [it, ["市妇幼保健院", "省人民医院", "区妇幼保健院"][i % 3], "绿色通道 · 已对接"]
            elif kind == "visit":
                mid = [it, "%02d-%02d" % (4 + i, 12 + i), ["已完成", "待访视", "家长已确认"][i % 3]]
            else:
                mid = [it, "%02d-%02d" % (4 + (mi + i) % 3, 8 + i * 3), doctor]
            tagv = ["info|进行中", "attention|待处理", "positive|已完成"][i % 3]
            act, after = [("记录结果", "positive|已完成"), ("安排随访", "info|随访中"),
                          ("推进处理", "positive|已归档")][i % 3]
            rows.append((who, mid, tagv, act, after))
        dk = d.get("kpis", [])
        if dk:
            kpis = [(k[0], k[1], k[2], k[3] if len(k) > 3 else _KPI_TONES[i % 5]) for i, k in enumerate(dk[:4])]
        else:
            kpis = [((subs[i] if i < len(subs) else name), _demo_count(pid, mi, i), "本周期", _KPI_TONES[i % 5])
                    for i in range(4)]
        out.append({
            "key": "m%d" % (mi + 1), "name": name,
            "desc": (" · ".join(subs[:4]) if subs else name + " · 本模块台账与处理"),
            "kpis": kpis, "cols": cols, "rows": rows,
            "side": ("子模块", [(s, "在管 %s" % _demo_count(pid, mi, i)) for i, s in enumerate(subs)]
                     or [(name, "本周期台账 · 责任人 " + doctor)]),
            "todo": ("待办提醒", ["本周期待处理 %s 项" % _demo_count(pid, mi, 9),
                                "%s 需在本月内完成复核" % things[0]]),
        })
    return out
